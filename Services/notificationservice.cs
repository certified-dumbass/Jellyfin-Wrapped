using System;
using System.Collections.Generic;
using System.Linq;

namespace Wrapped.Core.Services;

public class NotificationService
{
    private readonly List<StandardNotification> _notifications = new();
    private readonly object _lock = new();

    /// <summary>
    /// Fired whenever a new notification is created.
    /// Other Standard plugins can subscribe to this event.
    /// </summary>
    public event EventHandler<StandardNotification>? NotificationCreated;

    /// <summary>
    /// Creates a new informational notification.
    /// </summary>
    public StandardNotification Info(
        string title,
        string message,
        string source = "Standard Core")
    {
        return CreateNotification(
            title,
            message,
            NotificationType.Info,
            source);
    }

    /// <summary>
    /// Creates a success notification.
    /// </summary>
    public StandardNotification Success(
        string title,
        string message,
        string source = "Standard Core")
    {
        return CreateNotification(
            title,
            message,
            NotificationType.Success,
            source);
    }

    /// <summary>
    /// Creates a warning notification.
    /// </summary>
    public StandardNotification Warning(
        string title,
        string message,
        string source = "Standard Core")
    {
        return CreateNotification(
            title,
            message,
            NotificationType.Warning,
            source);
    }

    /// <summary>
    /// Creates an error notification.
    /// </summary>
    public StandardNotification Error(
        string title,
        string message,
        string source = "Standard Core")
    {
        return CreateNotification(
            title,
            message,
            NotificationType.Error,
            source);
    }

    /// <summary>
    /// Returns the most recent notifications.
    /// </summary>
    public IReadOnlyList<StandardNotification> GetNotifications(int limit = 50)
    {
        lock (_lock)
        {
            return _notifications
                .OrderByDescending(x => x.CreatedAt)
                .Take(Math.Clamp(limit, 1, 250))
                .Select(CloneNotification)
                .ToList()
                .AsReadOnly();
        }
    }

    /// <summary>
    /// Marks a notification as read.
    /// </summary>
    public bool MarkAsRead(Guid notificationId)
    {
        lock (_lock)
        {
            var notification =
                _notifications.FirstOrDefault(x => x.Id == notificationId);

            if (notification is null)
            {
                return false;
            }

            notification.IsRead = true;
            return true;
        }
    }

    /// <summary>
    /// Removes all notifications.
    /// </summary>
    public void Clear()
    {
        lock (_lock)
        {
            _notifications.Clear();
        }
    }

    private StandardNotification CreateNotification(
        string title,
        string message,
        NotificationType type,
        string source)
    {
        var notification = new StandardNotification
        {
            Id = Guid.NewGuid(),
            Title = title,
            Message = message,
            Type = type,
            Source = source,
            CreatedAt = DateTime.UtcNow,
            IsRead = false
        };

        lock (_lock)
        {
            _notifications.Add(notification);

            // Prevent the in-memory history from growing forever.
            if (_notifications.Count > 500)
            {
                _notifications.RemoveRange(
                    0,
                    _notifications.Count - 500);
            }
        }

        NotificationCreated?.Invoke(
            this,
            CloneNotification(notification));

        return CloneNotification(notification);
    }

    private static StandardNotification CloneNotification(
        StandardNotification notification)
    {
        return new StandardNotification
        {
            Id = notification.Id,
            Title = notification.Title,
            Message = notification.Message,
            Type = notification.Type,
            Source = notification.Source,
            CreatedAt = notification.CreatedAt,
            IsRead = notification.IsRead
        };
    }
}

/// <summary>
/// A notification generated by Standard Core or another Standard plugin.
/// </summary>
public class StandardNotification
{
    public Guid Id { get; set; }

    public string Title { get; set; } = string.Empty;

    public string Message { get; set; } = string.Empty;

    public NotificationType Type { get; set; }

    public string Source { get; set; } = string.Empty;

    public DateTime CreatedAt { get; set; }

    public bool IsRead { get; set; }
}

public enum NotificationType
{
    Info,
    Success,
    Warning,
    Error
}